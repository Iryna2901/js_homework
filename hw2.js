let x = 2;
let y = 9;

function pow(x, y) {
  let result = 1; // ми створюємо змінну result і ініціалізуємо її значенням 1. Це буде початкове значення, яке ми будемо множити на x протягом циклу.
  for (let i = 0; i < y; i++) {
    // запускаємо цикл, який буде виконуватися y разів і поки i менше y  тобто true, ми будемо множити result на x
    result *= x; // кожного разу, коли цикл виконується, ми множимо поточне значення result на x і зберігаємо результат назад у змінну result. Оператор = означає що ми переприсвоюємо змінній result нове значення(result = result * x; це те саме що result *= x);
    // а коли цикл false, тобто коли i досягне значення y, ми вийдемо з циклу і повернемо результат. Таким чином, ми отримаємо x, помножене саме на себе y разів, що є визначенням ступеня.
  }
  return result; // після завершення циклу ми повертаємо результат, який містить значення x, помножене саме на себе y разів.
}
console.log(pow(x, y));

